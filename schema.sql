-- NOVA AI catalog schema for Supabase (PostgreSQL)
-- Run this in Supabase SQL Editor.
-- Do NOT put a service_role key in client-side code or expose it publicly.

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    name text not null,
    category text not null,
    price numeric(10,2) not null check (price >= 0),
    original_price numeric(10,2),
    color text,
    sizes jsonb not null default '["Free Size"]'::jsonb,
    description text,
    image_url text not null,
    stock integer not null default 0 check (stock >= 0),
    active boolean not null default true,
    created_at timestamptz not null default now()
);

alter table public.products enable row level security;

-- Public read-only catalog policy. Only use public catalog fields in this table.
drop policy if exists "Anyone can read active products" on public.products;
create policy "Anyone can read active products"
on public.products for select
using (active = true);

